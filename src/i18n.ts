export function text(value: LocalizedText, language: Language): string {
  return value[language]
}

export function t(language: Language, key: string): string {
  return translations[language][key] ?? translations.en[key] ?? key
}

function pluralRu(count: number, one: string, few: string, many: string): string {
  const mod100 = Math.abs(count) % 100
  const mod10 = mod100 % 10
  if (mod100 >= 11 && mod100 <= 14) return many
  if (mod10 === 1) return one
  if (mod10 >= 2 && mod10 <= 4) return few
  return many
}

/**
 * Picks the correct plural form for a counted noun. English needs one word,
 * Russian needs three, so the choice cannot be a plain ternary in the caller.
 */
export function countLabel(
  language: Language,
  count: number,
  key: 'profile' | 'session' | 'character',
): string {
  const forms = translations[language]
  if (language === 'en') return `${count} ${forms[`${key}s` as keyof typeof forms]}`
  const one = forms[`${key}One` as keyof typeof forms]
  const few = forms[`${key}Few` as keyof typeof forms] ?? forms[`${key}Two` as keyof typeof forms]
  const many = forms[`${key}Many` as keyof typeof forms] ?? forms[`${key}s` as keyof typeof forms]
  return `${count} ${pluralRu(count, String(one), String(few), String(many))}`
}
